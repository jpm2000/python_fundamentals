# Operadores de comparacion

x = 5
y = 3
z = 5

print(x == y)
print(x == 5)
print(x != y)
print(x > y)
print(x < y)
print(x <= y)
print(x >= y)
print(x >= z)

# Operadores logicos

# Primera condicion va a ser true y la segunda false
print(x > y and y > z)
print(x > y or y > z)

v = True
f = False

print(not (v))
print(not (f))
